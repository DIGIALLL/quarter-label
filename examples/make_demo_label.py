"""Generates examples/demo-label.pdf: a fake courier label (all data invented),
laid out like many real ones: A4 landscape page, label rotated in the top-left corner."""
import random
from pathlib import Path
import pymupdf

MM = 72 / 25.4
FONT = "C:/Windows/Fonts/arial.ttf"
FONTB = "C:/Windows/Fonts/arialbd.ttf"
W, H = 96 * MM, 135 * MM

lab = pymupdf.open()
p = lab.new_page(width=W, height=H)
p.insert_font(fontname="a", fontfile=FONT)
p.insert_font(fontname="b", fontfile=FONTB)
p.draw_rect(p.rect + (1, 1, -1, -1), width=0.8)


def box(y0, y1):
    p.draw_line((1, y1 * MM), (W - 1, y1 * MM), width=0.6)


def txt(x, y, s, size=8, bold=False):
    p.insert_text((x * MM, y * MM), s, fontname="b" if bold else "a", fontsize=size)


txt(4, 9, "DEMO PARCEL", 16, True)
txt(66, 9, "DEPOT 07", 9, True)
box(0, 13)
txt(4, 19, "Tracking no.:", 7)
txt(4, 25, "0000 1234 5678 90", 12, True)
box(0, 29)
random.seed(7)
x = 8.0
while x < 88:
    w = random.choice([0.35, 0.35, 0.7, 1.0])
    p.draw_rect(pymupdf.Rect(x * MM, 32 * MM, (x + w) * MM, 50 * MM), color=None, fill=(0, 0, 0))
    x += w + random.choice([0.35, 0.7, 0.7, 1.0])
box(0, 54)
txt(4, 60, "Sender", 7)
txt(4, 65, "Jan Kowalski", 9, True)
txt(4, 69.5, "ul. Przykładowa 1, 00-001 Warszawa", 8)
box(0, 74)
txt(4, 80, "Recipient", 7)
txt(4, 86, "Anna Nowak", 11, True)
txt(4, 91.5, "ul. Testowa 22/5", 9)
txt(4, 96.5, "30-002 Kraków", 9)
box(0, 101)
txt(4, 107, "Size: M      Weight: 2.5 kg      Paid", 8)
box(0, 111)
txt(4, 120, "Sample label — all data is fictional", 9, True)
txt(4, 126, "generated by examples/make_demo_label.py", 7)

out = pymupdf.open()
a4 = out.new_page(width=297 * MM, height=210 * MM)
# rotated so that text runs top-to-bottom, like many courier PDFs
a4.show_pdf_page(pymupdf.Rect(8, 6, 8 + H, 6 + W), lab, 0, rotate=-90)
out.save(Path(__file__).with_name("demo-label.pdf"))
print("saved")
